let mixedInputDisplayInstalled=false;
function installMixedInputDisplay(){
  if(mixedInputDisplayInstalled)return;
  let installed=false;
  for(const prototype of [globalThis.HTMLInputElement?.prototype,globalThis.HTMLTextAreaElement?.prototype]){
    const descriptor=prototype&&Object.getOwnPropertyDescriptor(prototype,'value');
    if(!descriptor?.configurable||!descriptor.get||!descriptor.set)continue;
    const get=descriptor.get,set=descriptor.set;
    Object.defineProperty(prototype,'value',{configurable:true,enumerable:descriptor.enumerable,get(){const value=get.call(this);if(value==='Mixed'&&!this.isContentEditable&&!isComponentUserNameContext(this))return '多个值';return value;},set(value){set.call(this,value==='Mixed'&&!this.isContentEditable&&!isComponentUserNameContext(this)?'多个值':value);}});
    installed=true;
  }
  if(!installed)return;
  mixedInputDisplayInstalled=true;
}
function translateMixedTextNode(node){
  if(!node||node.nodeType!==Node.TEXT_NODE||node.nodeValue.trim()!=='Mixed')return false;
  const element=node.parentElement;
  if(!element||isComponentUserNameContext(element)||isCodeSyntaxContext(element))return false;
  const value=node.nodeValue;
  const leading=value.match(/^\s*/)?.[0]??'',trailing=value.match(/\s*$/)?.[0]??'';
  applyTranslatedText(node,value,`${leading}多个值${trailing}`);
  return true;
}
function translateTextNode(node){
  if(translateConnectedTeamFragments(node))return;
  if(translateMixedTextNode(node))return;
  const value=node.nodeValue;
  const translated=lookup(value,node);
  if(translated&&translated!==value)applyTranslatedText(node,value,translated);
}
function translateNode(node){
  if(!node)return;
  if(node.nodeType===Node.TEXT_NODE){translateTextNode(node);compactMotionBetaTooltip(node);return;}
  if(node.nodeType!==Node.ELEMENT_NODE&&node.nodeType!==Node.DOCUMENT_FRAGMENT_NODE)return;
  if(node.nodeType===Node.ELEMENT_NODE){translateFolderTransferPlanElement(node);translateControlledAutoValue(node);translateReadonlyMixedValue(node);translateAttributes(node);}
  const walker=document.createTreeWalker(node,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
  let current;while(current=walker.nextNode()){
    if(current.nodeType===Node.TEXT_NODE)translateTextNode(current);
    else{translateFolderTransferPlanElement(current);translateControlledAutoValue(current);translateReadonlyMixedValue(current);translateAttributes(current);}
  }
  compactMotionBetaTooltip(node);
}
function collectMutationRoots(records){
  const roots=new Set();
  for(const record of records){
    if(record.type==='characterData'||record.type==='attributes')roots.add(record.target);
    else for(const node of record.addedNodes)roots.add(node);
  }
  const result=[];
  rootLoop:for(const root of roots){
    for(let parent=root.parentNode;parent;parent=parent.parentNode){if(roots.has(parent))continue rootLoop;}
    result.push(root);
  }
  return result;
}
